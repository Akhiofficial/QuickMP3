import Razorpay from 'razorpay';
import crypto from 'crypto';
import config from '../../core/config/index.js';
import Transaction from './transaction.model.js';
import User from '../auth/auth.model.js';

// ─── Plan Config ────────────────────────────────────────────────────────────
